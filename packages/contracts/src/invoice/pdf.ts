// PDF rendering for an invoice document.
//
// ── WHY THIS IS THE DELIVERY HALF THAT IS NOT WAITING ON ANDRI ──────────
//
// The delivery decision (PDF vs PEPPOL) is still open, but round 1 found that
// customer 1 can pay a bank transfer against a PDF, needing only a bank
// account and an IBAN. So the PDF renderer is option-independent: it is
// needed under every branch of that decision, and under the recommended one
// it is the whole delivery mechanism.
//
// The document model has existed since round 1 and NOTHING rendered it to a
// file. This is that.
//
// ── WHY NO LIBRARY ─────────────────────────────────────────────────────
//
// A PDF for a one-page invoice is a few hundred bytes of a well-documented
// container format. Taking a dependency would add a supply-chain surface, a
// bundle cost inside a Worker, and a version to track — for something that is
// mostly string concatenation. The generated bytes are asserted by a golden
// file, so a regression is visible in review.
//
// ── DETERMINISM IS A REQUIREMENT, NOT A NICETY ─────────────────────────
//
// No creation date, no producer string, no random ids, fixed object order.
// Two renders of the same document must be byte-identical, because that is
// what makes a golden file meaningful and what lets the delivery log hash a
// document to detect a duplicate send.
//
// ── ENCODING ───────────────────────────────────────────────────────────
//
// WinAnsiEncoding covers every character Icelandic needs — á é í ó ú ý þ æ ö ð
// and their capitals all sit in Latin-1 — so a standard Helvetica renders the
// header without embedding a font.
//
// But WinAnsi is NOT Latin-1, and assuming it was produced a real bug on the
// first render: the header's EN DASH would have been written as byte 0x13, a
// device-control character. See `WIN_ANSI` below. Anything genuinely
// unrepresentable is replaced with "?" and REPORTED by
// `pdfEncodingProblems`, because a silently mangled legal name on an invoice
// is exactly the class of defect the header contract exists to prevent.

import type { InvoiceDocument } from "./document";
import { renderHeader } from "./header";

/**
 * WinAnsi is NOT Latin-1, and the difference matters here.
 *
 * WinAnsiEncoding fills 0x80–0x9F — which Latin-1 leaves as control codes —
 * with typographic characters. The header uses two of them: an EN DASH in
 * "Tímabil: from – to" and a MIDDLE DOT separator. Treating the string as
 * plain Latin-1 masks the en dash to 0x13, a device-control byte, and the
 * invoice renders with a control character where the period separator should
 * be.
 *
 * Caught by generating the golden file and reading it, which is the argument
 * for generating goldens rather than asserting them from imagination.
 */
const WIN_ANSI: ReadonlyMap<number, number> = new Map([
  [0x20ac, 0x80], // €
  [0x201a, 0x82],
  [0x0192, 0x83],
  [0x201e, 0x84],
  [0x2026, 0x85], // …
  [0x2020, 0x86],
  [0x2021, 0x87],
  [0x02c6, 0x88],
  [0x2030, 0x89],
  [0x0160, 0x8a],
  [0x2039, 0x8b],
  [0x0152, 0x8c],
  [0x017d, 0x8e],
  [0x2018, 0x91], // ‘
  [0x2019, 0x92], // ’
  [0x201c, 0x93], // “
  [0x201d, 0x94], // ”
  [0x2022, 0x95], // •
  [0x2013, 0x96], // – EN DASH — used by the period line
  [0x2014, 0x97], // —
  [0x02dc, 0x98],
  [0x2122, 0x99],
  [0x0161, 0x9a],
  [0x203a, 0x9b],
  [0x0153, 0x9c],
  [0x017e, 0x9e],
  [0x0178, 0x9f],
]);

/** The WinAnsi byte for a code point, or null when it cannot be represented. */
function winAnsiByte(cp: number): number | null {
  if (cp <= 0xff) {
    // 0x80–0x9F are control codes in Latin-1 and typographic in WinAnsi; a
    // raw control character has no business on an invoice either way.
    if (cp >= 0x80 && cp <= 0x9f) return null;
    return cp;
  }
  return WIN_ANSI.get(cp) ?? null;
}

/** Characters that cannot be represented in WinAnsi, with their positions. */
export function pdfEncodingProblems(doc: InvoiceDocument): string[] {
  const problems: string[] = [];
  const check = (label: string, value: string) => {
    for (const ch of value) {
      if (winAnsiByte(ch.codePointAt(0)!) === null) {
        problems.push(
          `${label} contains a character WinAnsiEncoding cannot represent: U+${ch
            .codePointAt(0)!
            .toString(16)
            .toUpperCase()}`,
        );
        break;
      }
    }
  };
  check("claimHolder.legalName", doc.claimHolder.legalName);
  check("recipient.legalName", doc.recipient.legalName);
  if (doc.presenter) check("presenter.legalName", doc.presenter.legalName);
  doc.lines.forEach((l, i) => check(`lines[${i}].description`, l.description));
  return problems;
}

export class PdfRenderError extends Error {
  readonly code: string;
  constructor(code: string, message: string) {
    super(message);
    this.name = "PdfRenderError";
    this.code = code;
  }
}

/** Escape a string for a PDF literal, then encode as Latin-1 bytes. */
function pdfLiteral(s: string): string {
  let out = "";
  for (const ch of s) {
    const b = winAnsiByte(ch.codePointAt(0)!);
    // Unrepresentable characters become "?" rather than a mangled byte.
    // pdfEncodingProblems reports them so the substitution is never silent.
    const c = b === null ? "?" : String.fromCharCode(b);
    if (c === "(" || c === ")" || c === "\\") out += "\\" + c;
    else out += c;
  }
  return out;
}

function latin1Bytes(s: string): Uint8Array {
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i) & 0xff;
  return out;
}

const FONT_SIZE = 10;
const LEADING = 14;
const LEFT = 56;
const TOP = 780;

function formatAmount(minor: number): string {
  // ISK has no minor unit in circulation, so the integer IS the amount.
  // Thousands separated with "." and no decimals, which is the Icelandic
  // convention and matches what A's dry run printed (7.564,00 kr uses "," for
  // decimals; we have none, so no decimal part is emitted).
  const neg = minor < 0;
  const digits = Math.abs(minor).toString();
  let grouped = "";
  for (let i = 0; i < digits.length; i++) {
    if (i > 0 && (digits.length - i) % 3 === 0) grouped += ".";
    grouped += digits[i];
  }
  return `${neg ? "-" : ""}${grouped}`;
}

/**
 * The page's text lines, in order.
 *
 * Exported so a test can assert CONTENT without parsing PDF syntax — the
 * golden file pins the bytes, this pins the meaning, and the two failing
 * together tells you something different from either failing alone.
 */
export function invoiceTextLines(doc: InvoiceDocument): string[] {
  // renderHeader is the guard: mixed posture, missing kroefuhafi identity and
  // a presenter that equals the claim holder all throw here rather than
  // rendering. The PDF path therefore inherits every header refusal for free.
  const h = renderHeader(doc);

  const lines: string[] = [];
  lines.push(h.documentLine);
  lines.push("");
  lines.push("KROFUHAFI");
  lines.push(h.claimLine);
  lines.push(h.claimHolderIdLine);
  lines.push(h.vatLine);
  if (h.presenterNote) {
    lines.push("");
    lines.push(h.presenterNote);
  }
  lines.push("");
  lines.push("GREIDANDI");
  for (const r of h.recipientLines) lines.push(r);
  lines.push("");
  lines.push(h.periodLine);
  lines.push(h.datesLine);
  lines.push("");
  lines.push("LIDIR");
  for (const l of doc.lines) {
    const amount = Math.round(l.quantity * l.unitPrice);
    lines.push(
      `${l.description}  —  ${l.quantity} x ${formatAmount(l.unitPrice)} = ${formatAmount(amount)} ${doc.currency}`,
    );
  }
  lines.push("");
  for (const b of doc.totals.byVatRate) {
    lines.push(`Nettó (${b.ratePercent}%): ${formatAmount(b.net)}   VSK: ${formatAmount(b.vat)}`);
  }
  lines.push(`Samtals án VSK: ${formatAmount(doc.totals.net)} ${doc.currency}`);
  lines.push(`VSK samtals:    ${formatAmount(doc.totals.vat)} ${doc.currency}`);
  lines.push(`SAMTALS:        ${formatAmount(doc.totals.gross)} ${doc.currency}`);
  return lines;
}

/**
 * Render the document to PDF bytes.
 *
 * Throws rather than returning a partial document — a half-rendered invoice
 * is worse than none, and every refusal here is a header refusal, which is
 * the legal artefact.
 */
export function renderInvoicePdf(doc: InvoiceDocument): Uint8Array {
  const textLines = invoiceTextLines(doc);

  // Build the content stream.
  const content: string[] = [];
  content.push("BT");
  content.push(`/F1 ${FONT_SIZE} Tf`);
  content.push(`${LEADING} TL`);
  content.push(`${LEFT} ${TOP} Td`);
  for (const line of textLines) {
    content.push(`(${pdfLiteral(line)}) Tj`);
    content.push("T*");
  }
  content.push("ET");
  const stream = content.join("\n");

  const objects: string[] = [];
  objects.push("<< /Type /Catalog /Pages 2 0 R >>");
  objects.push("<< /Type /Pages /Kids [3 0 R] /Count 1 >>");
  objects.push(
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
  );
  objects.push(`<< /Length ${latin1Bytes(stream).length} >>\nstream\n${stream}\nendstream`);
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>");

  // Assemble with a correct xref table. Deliberately no /Info dictionary:
  // no CreationDate, no Producer, nothing that changes between runs.
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, i) => {
    offsets.push(latin1Bytes(pdf).length);
    pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = latin1Bytes(pdf).length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (const off of offsets) pdf += `${String(off).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return latin1Bytes(pdf);
}

/** Convenience for callers that want a stable identity for a rendered document. */
export function pdfByteLength(doc: InvoiceDocument): number {
  return renderInvoicePdf(doc).length;
}
