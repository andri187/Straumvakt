// Deployment boundary: runs before both the Next server and static assets.
// Do not expose the retained legacy public/ HTML or operational routes.
// The page and asset lists are exact: a new route or image is public only
// when it is added here (scripts/prepare-cpo-shell-assets.mjs reads this list)
// and in src/lib/cpo-shell-policy.ts; scripts/cpo-shell-edge.test.mjs checks both.
// Files that exist in the generated assets directory and are served by ASSETS.
export const PUBLIC_ASSET_PATHS = [
  '/landing/straumvakt-logo-icon.png',
  '/landing/straumvakt-car.avif',
  '/landing/straumvakt-car.webp',
];
// Public files generated by the Next application itself (metadata routes).
export const APP_PUBLIC_PATHS = ['/icon.svg'];
export const PAGE_PATHS = [
  '/', '/signin',
  '/cpo', '/cpo/people', '/cpo/installations', '/cpo/chargers', '/cpo/sessions',
  '/cpo/costs', '/cpo/agreements', '/cpo/settings',
  // Protected redirect kept for the earlier Organisations menu entry.
  '/cpo/organisations',
];
export const API_PATHS = ['/api/shell/login', '/api/shell/logout', '/api/cpo/installations', '/api/cpo/directory', '/api/cpo/sync', '/api/cpo/lifecycle'];

const assets = new Set(PUBLIC_ASSET_PATHS);
const pages = new Set(PAGE_PATHS);
const api = new Set(API_PATHS);
const appPublic = new Set(APP_PUBLIC_PATHS);

export function createShellEdge(application) {
  return async function fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.hostname === 'straumvakt.org') {
      url.protocol = 'https:';
      url.hostname = 'www.straumvakt.org';
      url.port = '';
      return Response.redirect(url.toString(), 308);
    }
    const { pathname } = url;
    if (pathname === '/api/cpo/sync') {
      const socket = request.headers.get('upgrade')?.toLowerCase() === 'websocket';
      // A driver app authenticates with a bearer token, not the browser cookie. Such a GET (the follow-list, or a socket) is
      // answered by the realtime module only; without a cookie the application would have refused it anyway.
      const driver = request.method === 'GET' && /^Bearer\s/i.test(request.headers.get('authorization') ?? '');
      if (socket || driver) {
        if (env.CPO_SHELL_REALTIME_ENABLED !== 'true' || !env.VERSION_HUB) return new Response('Not found', { status: 404 });
        // Keep the optional runtime out of the plain-Node asset preparation import.
        const { realtimeUpgrade } = await import('./cpo-shell-realtime.mjs');
        return realtimeUpgrade(request, env);
      }
    }
    const asset = assets.has(pathname) || pathname.startsWith('/_next/static/');
    if (!asset && !pages.has(pathname) && !api.has(pathname) && !appPublic.has(pathname)) {
      return new Response('Not found', { status: 404, headers: { 'cache-control': 'no-store' } });
    }
    if (pathname === '/api/shell/login' && request.method === 'POST') {
      // Cloudflare supplies this header at the public ingress. Never trust X-Forwarded-For.
      const ip = request.headers.get('cf-connecting-ip');
      if (!env.SHELL_LOGIN_LIMITER || !ip) {
        return new Response('Sign-in is temporarily unavailable.', { status: 503 });
      }
      const result = await env.SHELL_LOGIN_LIMITER.limit({ key: `shell-login:${ip}` });
      if (!result.success) {
        return new Response('Too many sign-in attempts. Please wait a minute.', {
          status: 429, headers: { 'retry-after': '60', 'cache-control': 'no-store' },
        });
      }
    }
    const response = asset
      ? await env.ASSETS.fetch(request)
      : await application.fetch(request, env, ctx);
    const headers = new Headers(response.headers);
    headers.set('X-Robots-Tag', 'noindex, nofollow');
    headers.set('X-Content-Type-Options', 'nosniff');
    headers.set('Referrer-Policy', 'same-origin');
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
  };
}
